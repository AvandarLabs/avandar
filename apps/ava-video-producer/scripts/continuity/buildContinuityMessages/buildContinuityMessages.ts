import fs from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { requireLicense } from "../../require-license.mjs";
import { collectContinuityMessages } from "../collectContinuityMessages/collectContinuityMessages";

async function _writeChanged(options: { filename: string; source: string }) {
  const { filename, source } = options;
  if ((await fs.readFile(filename, "utf8").catch(() => "")) !== source) {
    await fs.writeFile(filename, source);
  }
}

function _buildCatalogRegistryFromLocales(locales: readonly string[]): string {
  const imports = locales.map(
    (locale, index) =>
      `import { messages as locale${index} } from ${JSON.stringify(`./locales/${locale}/messages`)};`,
  );
  const fields = locales.map(
    (locale, index) => `  ${JSON.stringify(locale)}: locale${index},`,
  );
  return (
    '/** Generated by buildContinuityMessages. Do not edit. */\nimport type { Messages } from "@lingui/core";\n' +
    imports.join("\n") +
    "\nexport const continuityCatalogs: Readonly<Record<string, Messages>> = {\n" +
    fields.join("\n") +
    "\n};\n"
  );
}

/** Generates extractable descriptors and a registry of compiled locale catalogs. */
export async function buildContinuityMessages(root: string): Promise<void> {
  const messages = await collectContinuityMessages(root);
  const directory = path.join(root, "src/continuity/i18n");
  await fs.mkdir(path.join(directory, "locales/en"), { recursive: true });
  const descriptors = Object.entries(messages).map(([id, message]) => {
    const literal = message
      .replace(/'/g, "''")
      .replace(/[{}]/g, (brace) => `'${brace}'`);
    return `  msg({ id: ${JSON.stringify(id)}, message: ${JSON.stringify(literal)} }),`;
  });
  await _writeChanged({
    filename: path.join(directory, "descriptors.generated.ts"),
    source:
      '/** Generated by buildContinuityMessages. Do not edit. */\nimport { msg } from "@lingui/core/macro";\nexport const descriptors = [\n' +
      descriptors.join("\n") +
      "\n];\n",
  });
  await _writeChanged({
    filename: path.join(directory, "sourceMessages.generated.ts"),
    source:
      "/** Generated by buildContinuityMessages. Do not edit. */\nexport const sourceMessages: Record<string, string> = " +
      JSON.stringify(messages, null, 2) +
      ";\n",
  });
  const locales = (
    await fs.readdir(path.join(directory, "locales"), { withFileTypes: true })
  )
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();
  await _writeChanged({
    filename: path.join(directory, "catalogs.generated.ts"),
    source: _buildCatalogRegistryFromLocales(locales),
  });
}

if (
  process.argv[1] &&
  pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url
) {
  requireLicense();
  await buildContinuityMessages(process.cwd());
}
