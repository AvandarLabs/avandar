import fs from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { runInNewContext } from "node:vm";
import { compileMessage } from "@lingui/message-utils/compileMessage";
import { build } from "esbuild";
import { requireLicense } from "../../require-license.mjs";
import { yamlPlugin } from "../../yaml/yamlPlugin/yamlPlugin";
function _compileLiteral(message: string): string[] {
  const compiled = compileMessage(
    message.replace(/'/g, "''").replace(/[{}]/g, (brace) => `'${brace}'`),
  );
  if (
    !Array.isArray(compiled) ||
    !compiled.every((part) => typeof part === "string")
  ) {
    throw new Error("Stock copy must compile as literal text");
  }
  return compiled;
}

function _buildCatalogLiteral(
  messages: Record<string, string | string[]>,
): string {
  const fields = Object.entries(messages).map(([id, message]) => {
    const key = JSON.stringify(id);
    const value = Array.isArray(message)
      ? `[${message.map(_quote).join(", ")}]`
      : _quote(message);
    if (key.length + value.length + 5 <= 80) {
      return `  ${key}: ${value},`;
    }
    return Array.isArray(message)
      ? `  ${key}: [\n${message.map((part) => `    ${_quote(part)},`).join("\n")}\n  ],`
      : `  ${key}:\n    ${value},`;
  });
  return `{\n${fields.join("\n")}\n}`;
}

async function _loadCanonicalMessages(
  root: string,
): Promise<Record<string, string>> {
  const result = await build({
    absWorkingDir: root,
    stdin: {
      contents:
        'import { stockContracts } from "./src/stock/registry/stockContracts"; import { StockCopyMessages } from "./src/stock/i18n/StockCopyMessages"; export const sourceMessages = StockCopyMessages.getMessagesFromContract(stockContracts);',
      resolveDir: root,
    },
    bundle: true,
    plugins: [yamlPlugin],
    write: false,
    format: "cjs",
    platform: "node",
    logLevel: "silent",
  });
  const loaded = {
    exports: {} as {
      sourceMessages: Record<string, string>;
    },
  };
  runInNewContext(result.outputFiles[0].text, {
    module: loaded,
    exports: loaded.exports,
  });
  return loaded.exports.sourceMessages;
}

/**
 * Generates renderer-free English messages from fresh canonical stock sources.
 */
export async function buildStockMessages(root: string): Promise<void> {
  if (
    !(await fs
      .access(path.join(root, "src/stock/registry/stockContracts.ts"))
      .then(
        () => true,
        () => false,
      ))
  ) {
    return;
  }
  const sourceMessages = await _loadCanonicalMessages(root);
  const messages = Object.fromEntries(
    Object.entries(sourceMessages).map(([id, message]) => [
      id,
      _compileLiteral(message),
    ]),
  );
  const source = `/** Generated by buildStockMessages. Do not edit. */\nexport const sourceMessages: Record<string, string> = ${_buildCatalogLiteral(sourceMessages)};\nexport const messages = ${_buildCatalogLiteral(messages)};\n`;
  const filename = path.join(root, "src/stock/i18n/messages.en.generated.ts");
  const contents = source;
  if ((await fs.readFile(filename, "utf8").catch(() => "")) !== contents) {
    await fs.writeFile(filename, contents);
  }
}
function _quote(text: string): string {
  const literal = JSON.stringify(text);
  const doubleQuotes = text.split('"').length;
  const singleQuotes = text.split("'").length;
  return doubleQuotes > singleQuotes
    ? `'${literal.slice(1, -1).replace(/\\"/g, '"').replace(/'/g, "\\'")}'`
    : literal;
}
if (
  process.argv[1] &&
  pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url
) {
  requireLicense();
  await buildStockMessages(process.cwd());
}
