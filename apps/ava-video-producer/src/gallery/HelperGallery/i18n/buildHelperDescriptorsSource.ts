import type { HelperCatalog } from "../helperCatalog.types";

/** Message id prefix that keeps helper copy apart from other gallery copy. */
export const HELPER_MESSAGE_PREFIX = "helpers.";

/** Every authored sentence a reader sees: titles, descriptions and guidance. */
export function getHelperMessagesFromCatalog(catalog: HelperCatalog): string[] {
  const messages = [
    ...catalog.categories.flatMap((category) => [
      category.title,
      category.description,
    ]),
    ...catalog.helpers.flatMap((helper) => [
      helper.title,
      helper.description,
      helper.goodFor,
      helper.avoid,
    ]),
  ];
  return [...new Set(messages)].sort();
}

/** Escapes ICU syntax so authored braces and quotes stay literal. */
function _escapeMessage(message: string): string {
  return message.replace(/'/g, "''").replace(/[{}]/g, (brace) => `'${brace}'`);
}

/**
 * The source of `helperDescriptors.generated.ts`: one extractable Lingui
 * descriptor per authored helper sentence, so `gallery:messages` adds the
 * catalog copy to the gallery's translation catalog.
 */
export function buildHelperDescriptorsSource(catalog: HelperCatalog): string {
  const descriptors = getHelperMessagesFromCatalog(catalog).map(
    (message) =>
      `  msg({ id: ${JSON.stringify(HELPER_MESSAGE_PREFIX + message)}, message: ${JSON.stringify(_escapeMessage(message))} }),`,
  );
  return (
    "/** Generated by buildHelperMessages from helperCatalog.yaml. Do not edit. */\n" +
    'import { msg } from "@lingui/core/macro";\n\n' +
    "/** Extractable descriptors for the helper catalog's display copy. */\n" +
    "export const helperDescriptors = [\n" +
    descriptors.join("\n") +
    "\n];\n"
  );
}
