import { writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { readBundledPlugins } from "@plugin-manifest/node/readBundledPlugins.ts";
import type { PluginDirectory } from "@plugin-manifest/node/readPluginDirectory.ts";
import type { PluginAiTool } from "@plugin-manifest/PluginManifest/PluginManifestSchema.ts";

type NamedPluginAiTool = { pluginId: string; name: string };

type PluginAiToolEntry = PluginAiTool & {
  pluginId: string;
  permissions: readonly string[];
};

function _buildEntriesFromPlugin(plugin: PluginDirectory): PluginAiToolEntry[] {
  const { manifest } = plugin.compiled;
  return manifest.contributes.aiTools.map((tool) => {
    return {
      pluginId: manifest.id,
      permissions: manifest.permissions,
      ...tool,
    };
  });
}

/**
 * Throws when two plugins declare a data-agent tool with the same name, since
 * the model addresses a tool by name alone. The message names both plugins.
 *
 * Use it on any list of plugin tool declarations before they are offered to
 * the model, for example when the bundled tool list is generated.
 */
export function assertUniquePluginAiToolNames(
  tools: readonly NamedPluginAiTool[],
): void {
  const pluginIdByName = new Map<string, string>();
  tools.forEach((tool) => {
    const firstPluginId = pluginIdByName.get(tool.name);
    if (firstPluginId !== undefined) {
      throw new Error(
        `duplicate ai tool name "${tool.name}" on ${firstPluginId} and ${tool.pluginId}`,
      );
    }
    pluginIdByName.set(tool.name, tool.pluginId);
  });
}

/**
 * Makes the text of `shared/agent/dataAgent/pluginAiTools.gen.ts`: the
 * data-agent tools declared by every bundled plugin, in bundled order.
 *
 * Use it from a build step that writes the file, or from a test that checks
 * the committed file is current. Throws when two plugins declare the same
 * tool name.
 */
export function emitPluginAiToolsFile(repoRoot: string): string {
  const tools = readBundledPlugins(repoRoot).flatMap(_buildEntriesFromPlugin);
  assertUniquePluginAiToolNames(tools);
  return [
    "// Generated by packages/shared/plugin-manifest/src/node/emitPluginAiTools.ts.",
    "// Do not edit by hand. Run the emitter to regenerate it.",
    'import type { PluginAiToolDeclaration } from "$/agent/dataAgent/pluginAiTools.types.ts";',
    "",
    "/** Every data-agent tool declared by a bundled plugin. */",
    `export const PLUGIN_AI_TOOLS: readonly PluginAiToolDeclaration[] = ${JSON.stringify(tools, null, 2)};`,
    "",
  ].join("\n");
}

// `pnpm vite-script` runs this file under vite-node, which leaves its own
// entry in `process.argv[1]` instead of the script path. Importing the module
// from a test or another tool must not write the file.
if (process.argv[1]?.endsWith("vite-node.mjs") === true) {
  const repoRoot = resolve(
    fileURLToPath(new URL(".", import.meta.url)),
    "../../../../..",
  );
  writeFileSync(
    join(repoRoot, "shared/agent/dataAgent/pluginAiTools.gen.ts"),
    emitPluginAiToolsFile(repoRoot),
  );
}
